#!/usr/bin/env python3
"""
Generate a static Rust file with PERSONS constant.
This generates an rs file with all Person structs written statically,
equivalent to the dynamic make_persons() implementation.

Two modes are available:
1. Inline mode: All strings inline (simpler, but creates very large files)
2. Optimized mode: Shared string pools with indices (more memory efficient)
"""

import sys
from pathlib import Path


def generate_persons_rs_inline(
    output_file: str, num_persons: int = 1000000, chunk_size: int = 100000
):
    """
    Generate a Rust file with static PERSONS data (inline strings).
    WARNING: This generates a very large file for large num_persons values.

    Args:
        output_file: Path to output .rs file
        num_persons: Number of Person structs to generate
        chunk_size: Number of persons to write before progress update
    """

    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w") as f:
        # Write header and struct definition
        f.write(
            """//! Auto-generated static PERSONS constant
//! Generated by generate_persons.py (inline mode)

#[derive(Debug, Clone, Copy)]
struct Person {
    first_name: &'static str,
    last_name: &'static str,
    age: u8,
}

const PERSONS: &[Person] = &[
"""
        )

        # Generate all persons
        for i in range(num_persons):
            first_name = f"Jake {i}"
            last_name = f"Novak {i}"
            age = i % 100

            # Write person as a struct literal with inline strings
            f.write(
                f'    Person {{ first_name: "{first_name}", last_name: "{last_name}", age: {age} }},\n'
            )

            # Progress indicator every chunk_size persons
            if (i + 1) % chunk_size == 0:
                print(f"Generated {i + 1}/{num_persons} persons...", file=sys.stderr)

        # Write footer
        f.write(
            """];

pub fn make_persons() -> &'static [Person] {
    PERSONS
}
"""
        )

    print(f"Generated {num_persons} persons in {output_file}")


def generate_persons_rs_optimized(
    output_file: str, num_persons: int = 1000000, chunk_size: int = 100000
):
    """
    Generate a Rust file with static PERSONS data using optimized string pooling.
    Uses separate arrays for unique first/last names with indices.

    Args:
        output_file: Path to output .rs file
        num_persons: Number of Person structs to generate
        chunk_size: Number of persons to write before progress update
    """

    output_path = Path(output_file)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    # Collect all unique strings
    first_names = {}
    last_names = {}
    first_name_idx = 0
    last_name_idx = 0
    person_data = []

    print("Collecting unique strings...", file=sys.stderr)
    for i in range(num_persons):
        first_name = f"Jake {i}"
        last_name = f"Novak {i}"
        age = i % 100

        if first_name not in first_names:
            first_names[first_name] = first_name_idx
            first_name_idx += 1

        if last_name not in last_names:
            last_names[last_name] = last_name_idx
            last_name_idx += 1

        person_data.append((first_names[first_name], last_names[last_name], age))

        if (i + 1) % chunk_size == 0:
            print(f"Processed {i + 1}/{num_persons} persons...", file=sys.stderr)

    print("Writing output file...", file=sys.stderr)

    with open(output_path, "w") as f:
        # Write header
        f.write(
            """//! Auto-generated static PERSONS constant
//! Generated by generate_persons.py (optimized mode with string pooling)

#[derive(Debug, Clone, Copy)]
struct Person {
    first_name: &'static str,
    last_name: &'static str,
    age: u8,
}

const FIRST_NAMES: &[&str] = &[
"""
        )

        # Write first names
        for name, idx in sorted(first_names.items(), key=lambda x: x[1]):
            f.write(f'    "{name}",\n')

        f.write(
            """];

const LAST_NAMES: &[&str] = &[
"""
        )

        # Write last names
        for name, idx in sorted(last_names.items(), key=lambda x: x[1]):
            f.write(f'    "{name}",\n')

        f.write(
            """];

const PERSONS_DATA: &[(usize, usize, u8)] = &[
"""
        )

        # Write person data as indices
        for fn_idx, ln_idx, age in person_data:
            f.write(f"    ({fn_idx}, {ln_idx}, {age}),\n")

        f.write(
            """];

pub fn make_persons() -> Vec<Person> {
    PERSONS_DATA
        .iter()
        .map(|&(fn_idx, ln_idx, age)| Person {
            first_name: FIRST_NAMES[fn_idx],
            last_name: LAST_NAMES[ln_idx],
            age,
        })
        .collect()
}
"""
        )

    print(
        f"Generated {num_persons} persons with {len(first_names)} unique first names and {len(last_names)} unique last names in {output_file}"
    )


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: generate_persons.py <output_file> [num_persons] [mode]")
        print("  mode: 'inline' (default) or 'optimized'")
        sys.exit(1)

    output_file = sys.argv[1]
    num_persons = int(sys.argv[2]) if len(sys.argv) > 2 else 1000000
    mode = sys.argv[3].lower() if len(sys.argv) > 3 else "inline"

    if mode == "optimized":
        generate_persons_rs_optimized(output_file, num_persons)
    else:
        generate_persons_rs_inline(output_file, num_persons)
